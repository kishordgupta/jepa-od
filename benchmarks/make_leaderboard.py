"""Leaderboard of every TSJEPAOD version on TSB-AD with all nine measures (LEADERBOARD.md, REPORT.md section 7.12).

Reads results/tsb/metrics/<list>/<run>.csv (benchmarks/eval_tsb.py: one row per series and score type with the nine
measures of jepa_od/metrics.py) for the five lists, which together are all 200 multivariate and all 870 univariate
series of TSB-AD, and TSB-AD's published per-series VUS-PR (data/tsb_published/). Writes

* results/leaderboard/tsb_nine_measures.csv: the mean of every measure for every run, score type and list, and for
  the two sets pooled ("M-all", "U-all");
* LEADERBOARD.md: the tables below.
"""
import os, re, sys, glob
import numpy as np, pandas as pd
from scipy.stats import spearmanr

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _tables import md

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, 'results', 'tsb')
PUB = os.path.join(ROOT, 'data', 'tsb_published')
VERSIONS = ['lejepa', 'ijepa', 'tsjepa', 'tjepa', 'vjepa', 'vjepa21', 'cjepa', 'sjepa', 'salt', 'vicreg', 'kerjepa',
            'lpjepa', 'lambdajepa', 'lenepa', 'lewm', 'cfjepa', 'ststjepa', 'hepa', 'subjepa', 'straight',
            'motionjepa', 'njepa', 'gmmjepa', 'variational', 'phijepa', 'harjepa']
CONTROL = {'subjepa': 'lewm', 'straight': 'lewm', 'motionjepa': 'lewm'}   # same untrained network
MEASURES = ['VUS-PR', 'VUS-ROC', 'AUC-PR', 'AUC-ROC', 'Standard-F1', 'PA-F1', 'Event-based-F1', 'R-based-F1',
            'Affiliation-F']
LISTS = {'M-Eva': 180, 'M-Tuning': 20, 'U-Eva': 350, 'U-Tuning': 48, 'U-Rest': 472}
SETS = {'M-all': ['M-Eva', 'M-Tuning'], 'U-all': ['U-Eva', 'U-Tuning', 'U-Rest']}
REF = {'M': ('ref_PCA_slidingWindow1', "TSB-AD's PCA (window 1), re-run"),
       'U': ('ref_Sub_PCA', "TSB-AD's Sub-PCA, re-run")}
SCORES = ('pred', 'embed', 'combined')

frames = []
for lst, n in LISTS.items():
    for path in sorted(glob.glob(os.path.join(R, 'metrics', lst, '*.csv'))):
        tag = os.path.basename(path)[:-4]
        d = pd.read_csv(path).drop_duplicates(['file', 'score'])
        d['list'], d['run'] = lst, tag
        frames.append(d[['list', 'run', 'file', 'score'] + MEASURES])
per_file = pd.concat(frames, ignore_index=True)
for m in MEASURES:
    per_file[m] = pd.to_numeric(per_file[m], errors='coerce')


def describe(tag):
    """(version, training) of a run name; None for the runs that are not part of the leaderboard."""
    if tag == 'rawpatch_s42_semi':
        return 'no network (raw patches)', '-'
    if tag.startswith('ref_'):
        return {'ref_PCA_slidingWindow1': REF['M'][1], 'ref_Sub_PCA': REF['U'][1]}.get(tag), '-'
    m = re.fullmatch(r'([a-z0-9]+)_(trained|e0)_s42_semi', tag)
    return (m.group(1), 'trained' if m.group(2) == 'trained' else 'untrained') if m else (None, None)


per_file['version'], per_file['training'] = zip(*per_file.run.map(describe))
per_file = per_file[per_file.version.notna()]
# the three versions on the network of lewm share its untrained control
extra = []
for v, source in CONTROL.items():
    d = per_file[(per_file.version == source) & (per_file.training == 'untrained')].copy()
    d['version'] = v
    extra.append(d)
per_file = pd.concat([per_file] + extra, ignore_index=True)
complete = per_file.groupby(['list', 'version', 'training', 'score']).file.nunique().reset_index(name='n')
complete = complete[complete.n == complete.list.map(LISTS)]
per_file = per_file.merge(complete[['list', 'version', 'training', 'score']], on=['list', 'version', 'training', 'score'])
by_list = per_file.groupby(['list', 'version', 'training', 'score'])[MEASURES].mean()
by_list['series'] = per_file.groupby(['list', 'version', 'training', 'score']).file.nunique()
pooled = []
for name, lists in SETS.items():
    d = per_file[per_file.list.isin(lists)]
    g = d.groupby(['version', 'training', 'score'])
    t = g[MEASURES].mean()
    t['series'] = g.file.nunique()
    t = t[t.series == sum(LISTS[l] for l in lists)].reset_index()
    t.insert(0, 'list', name)
    pooled.append(t)
table = pd.concat([by_list.reset_index()] + pooled, ignore_index=True)
os.makedirs(os.path.join(ROOT, 'results', 'leaderboard'), exist_ok=True)
table.to_csv(os.path.join(ROOT, 'results', 'leaderboard', 'tsb_nine_measures.csv'), index=False, float_format='%.4f')
T = table.set_index(['list', 'version', 'training', 'score'])


def row(lst, version, training, score):
    key = (lst, version, training, score)
    return T.loc[key] if key in T.index else None


def fmt(values, bold=None):
    return [f'**{v:.3f}**' if bold is not None and b else f'{v:.3f}' for v, b in zip(
        values, bold if bold is not None else [False] * len(values))]


out = ['# Leaderboard: every `TSJEPAOD` version on TSB-AD, nine measures', '',
       'Generated by `benchmarks/make_leaderboard.py` from `results/tsb/metrics/`. Do not edit by hand.', '',
       'Benchmark: TSB-AD (Liu and Paparrizos, NeurIPS 2024), all 200 multivariate and all 870 univariate series '
       '(its evaluation lists, its tuning lists and the 472 univariate series in neither). Protocol of '
       '`REPORT.md` Section 7.9: class defaults, no tuning, one seed (42), fit on the training prefix of each '
       'series, score the whole series. Measures: `jepa_od/metrics.py`, which gives the numbers of TSB-AD\'s own '
       'evaluation code (`benchmarks/check_metrics_tsb.py`). VUS-PR is the measure TSB-AD ranks by. The five F '
       'measures are the best over 100 thresholds, chosen with the labels; PA-F1 counts an anomaly as found in '
       'full after one hit and is close to 1 for many detectors.', '',
       'What the tables do not show: the differences between neighbouring rows are mostly not significant '
       '(tests: `REPORT.md` Sections 7.9 to 7.11), the versions were not tuned, and the control without any network '
       'is a row of its own because it is hard to beat on univariate series.', '']

for name, lists in SETS.items():
    n = sum(LISTS[l] for l in lists)
    s = name[0]
    for score in ('pred', 'embed', 'combined'):
        rows = []
        for v in VERSIONS:
            r = row(name, v, 'trained', score)
            if r is not None:
                rows.append((f'`{v}`' + (' (default)' if v == 'lejepa' else ''), r))
        if score == 'pred':
            r = row(name, 'lejepa', 'untrained', 'pred')
            rows.append(('`lejepa`, untrained', r))
            r = row(name, REF[s][1], '-', 'score')
            if r is not None:
                rows.append((REF[s][1], r))
        if score == 'embed':
            r = row(name, 'no network (raw patches)', '-', 'embed')
            if r is not None:
                rows.append(('no network (raw patches)', r))
            r = row(name, 'lejepa', 'untrained', 'embed')
            rows.append(('`lejepa`, untrained', r))
        rows = [x for x in rows if x[1] is not None]
        rows.sort(key=lambda x: -x[1]['VUS-PR'])
        d = pd.DataFrame([r[MEASURES].astype(float) for _, r in rows], index=[k for k, _ in rows])
        best = d.eq(d.max())
        shown = pd.DataFrame({m: fmt(d[m].values, best[m].values) for m in MEASURES}, index=d.index)
        shown.insert(0, 'place', range(1, len(shown) + 1))
        shown.index.name = 'version'
        what = {'pred': 'the default score `pred` (latent prediction error)',
                'embed': 'the score `embed` (Mahalanobis distance of patch embeddings)',
                'combined': 'the score `combined`'}[score]
        out += [f'## TSB-AD-{s}, all {n} series: {what}', '',
                f'Mean over the {n} series, trained versions unless a row says otherwise, sorted by VUS-PR; the '
                'highest value of a column is bold.', '', md(shown), '']

# places among TSB-AD's published detectors (VUS-PR, evaluation lists)
out += ['## Place among the detectors TSB-AD published (evaluation lists, VUS-PR)', '',
        'TSB-AD publishes per-series numbers for VUS-PR only, and only on its evaluation lists (180 multivariate, '
        '350 univariate series). Place: among the published detectors plus the row itself, by mean VUS-PR. The '
        'published numbers are as published; Section 7.10 of the report re-runs two of them.', '']
rows = []
pub = {s: pd.read_csv(os.path.join(PUB, f'{n}_mergedTable_VUS-PR.csv')) for s, n in (('M', 'multi'), ('U', 'uni'))}
for v in VERSIONS:
    r = {'version': f'`{v}`'}
    for s, lst in (('M', 'M-Eva'), ('U', 'U-Eva')):
        cols = [c for c in pub[s].columns if pub[s][c].dtype.kind == 'f' and c not in ('ts_len', 'anomaly_len',
                'num_anomaly', 'avg_anomaly_len', 'anomaly_ratio', 'point_anomaly', 'seq_anomaly')]
        means = pub[s][cols].mean()
        for score in ('pred', 'embed'):
            x = row(lst, v, 'trained', score)
            if x is None:
                r[f'{s} `{score}`'] = 'missing'
                continue
            r[f'{s} `{score}`'] = f'{x["VUS-PR"]:.3f} ({int((means > x["VUS-PR"]).sum()) + 1} of {len(means) + 1})'
    rows.append(r)
best = {s: (pub[s][[c for c in pub[s].columns if pub[s][c].dtype.kind == 'f' and c not in (
    'ts_len', 'anomaly_len', 'num_anomaly', 'avg_anomaly_len', 'anomaly_ratio', 'point_anomaly',
    'seq_anomaly')]].mean().sort_values(ascending=False)) for s in pub}
out += [md(pd.DataFrame(rows).set_index('version')), '',
        'Highest published means: multivariate ' + ', '.join(f'{k} {v:.3f}' for k, v in best['M'].head(3).items())
        + '; univariate ' + ', '.join(f'{k} {v:.3f}' for k, v in best['U'].head(3).items()) + '.', '']

# do the measures agree?
out += ['## Do the measures rank the versions alike?', '',
        'Spearman rank correlation, over the trained versions, between the mean VUS-PR and the mean of each other '
        'measure (score `pred`).', '']
rows = []
for name in SETS:
    d = pd.DataFrame({v: row(name, v, 'trained', 'pred')[MEASURES].astype(float) for v in VERSIONS
                      if row(name, v, 'trained', 'pred') is not None}).T
    r = {'set': f'TSB-AD-{name[0]} ({len(d)} versions)'}
    for m in MEASURES[1:]:
        r[m] = f'{spearmanr(d["VUS-PR"], d[m])[0]:+.2f}'
    rows.append(r)
out += [md(pd.DataFrame(rows).set_index('set')), '',
        'All means per list (the five lists and the two pooled sets), score type, and for trained and untrained '
        'runs: `results/leaderboard/tsb_nine_measures.csv`.', '']
text = '\n'.join(out)
open(os.path.join(ROOT, 'LEADERBOARD.md'), 'w').write(text)
print(text[:3000])
print('...', len(table), 'rows in the CSV')
